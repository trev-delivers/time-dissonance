#!/usr/bin/env node
/* Writes src/lib/dst-table.js: every time the clocks went forward in each
 * region in src/lib/regions.js, from 1900 to the end of TO_YEAR.
 *
 * The source is the IANA tz database, read through Node's Intl (Node 22
 * ships full ICU). Nothing here knows any daylight saving rules: it asks
 * Intl what the UTC offset was at each moment and records every rise.
 *
 *   npm run dst:generate          # rewrite the table
 *   npm run dst:generate -- --check   # exit 1 if the table is out of date
 *
 * Run it when Node's tz database version changes (process.versions.tz).
 * src/lib/dst.test.js fails if the committed table no longer matches.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { REGIONS } from "../src/lib/regions.js";

export const FROM_YEAR = 1900;
export const TO_YEAR = 2040;

const OUT = fileURLToPath(new URL("../src/lib/dst-table.js", import.meta.url));

const formatters = new Map();
function formatterFor(zone) {
  if (!formatters.has(zone)) {
    formatters.set(zone, new Intl.DateTimeFormat("en-GB", {
      timeZone: zone, hourCycle: "h23",
      year: "numeric", month: "numeric", day: "numeric",
      hour: "numeric", minute: "numeric", second: "numeric",
    }));
  }
  return formatters.get(zone);
}

/* Wall-clock fields for a UTC second in a zone. format() and a regex is
   about 3 times faster than formatToParts(), which matters over 140 years. */
const WALL = /^(\d+)\/(\d+)\/(\d+), (\d+):(\d+):(\d+)$/;
function wall(zone, sec) {
  const text = formatterFor(zone).format(new Date(sec * 1000));
  const m = WALL.exec(text);
  if (!m) throw new Error(`Unexpected date format from Intl: ${text}`);
  return { d: +m[1], mo: +m[2], y: +m[3], h: +m[4], mi: +m[5], s: +m[6] };
}

/* UTC offset in seconds at a UTC second. */
function offsetAt(zone, sec) {
  const w = wall(zone, sec);
  return Date.UTC(w.y, w.mo - 1, w.d, w.h, w.mi, w.s) / 1000 - sec;
}

/* First second in (lo, hi] whose offset differs from the offset at lo. */
function firstChange(zone, lo, hi) {
  const base = offsetAt(zone, lo);
  while (hi - lo > 1) {
    const mid = Math.floor((lo + hi) / 2);
    if (offsetAt(zone, mid) === base) lo = mid; else hi = mid;
  }
  return hi;
}

/* Every rise in UTC offset in a zone between two UTC seconds, as
   [local date after the jump as YYYYMMDD, UTC second, seconds skipped]. */
export function forwardJumps(zone, fromSec, toSec, step = 12 * 3600) {
  const out = [];
  let t = fromSec;
  let off = offsetAt(zone, t);
  while (t < toSec) {
    const next = Math.min(t + step, toSec);
    const nextOff = offsetAt(zone, next);
    if (nextOff === off) { t = next; continue; }
    const at = firstChange(zone, t, next);
    const after = offsetAt(zone, at);
    if (after > off) {
      const w = wall(zone, at);
      out.push([w.y * 10000 + w.mo * 100 + w.d, at, after - off]);
    }
    t = at;
    off = after;
  }
  return out;
}

export function buildTable() {
  const from = Date.UTC(FROM_YEAR, 0, 1) / 1000 - 86400;
  const to = Date.UTC(TO_YEAR + 1, 0, 1) / 1000;
  const table = {};
  for (const r of REGIONS) {
    if (!r.zone) continue;
    table[r.key] = forwardJumps(r.zone, from, to)
      .filter(([date]) => date >= FROM_YEAR * 10000);
  }
  return table;
}

export function render(table) {
  const lines = [
    "/* Generated by scripts/gen-dst.mjs from the IANA tz database. Don't edit by hand.",
    ` * tz database ${process.versions.tz}, years ${FROM_YEAR} to ${TO_YEAR}.`,
    " * Per region: [local date after the jump as YYYYMMDD, UTC seconds, seconds skipped]. */",
    `export const TZDB_VERSION = ${JSON.stringify(process.versions.tz)};`,
    `export const FROM_YEAR = ${FROM_YEAR};`,
    `export const TO_YEAR = ${TO_YEAR};`,
    "export const DST_TABLE = {",
  ];
  for (const [key, rows] of Object.entries(table)) {
    lines.push(`  ${JSON.stringify(key)}: [`);
    for (let i = 0; i < rows.length; i += 4) {
      lines.push("    " + rows.slice(i, i + 4).map((r) => JSON.stringify(r)).join(",") + ",");
    }
    lines.push("  ],");
  }
  lines.push("};", "");
  return lines.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render(buildTable());
  if (process.argv.includes("--check")) {
    const current = readFileSync(OUT, "utf8");
    if (current !== text) {
      console.error(`src/lib/dst-table.js is out of date for tz database ${process.versions.tz}. Run npm run dst:generate.`);
      process.exit(1);
    }
    console.log(`src/lib/dst-table.js matches tz database ${process.versions.tz}.`);
  } else {
    writeFileSync(OUT, text);
    console.log(`Wrote src/lib/dst-table.js from tz database ${process.versions.tz}.`);
  }
}
